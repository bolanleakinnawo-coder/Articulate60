const RECENT_KEY = "loquiex.research.recent";
const SESSION_KEY = "loquiex.research.session";

function readJson(key, fallback) {
  try {
    const raw = localStorage.getItem(key);
    return raw ? JSON.parse(raw) : fallback;
  } catch {
    return fallback;
  }
}

function writeJson(key, value) {
  try {
    if (value === null) localStorage.removeItem(key);
    else localStorage.setItem(key, JSON.stringify(value));
  } catch {
    // Storage can be unavailable (private mode). The flow still works.
  }
}

// A topic from the subject (or any subject when subjectId is null), avoiding
// the topics this member saw most recently.
export function pickResearchTopic(subjectId = null) {
  const pool = subjectId
    ? RESEARCH_SUBJECTS.filter((s) => s.id === subjectId)
    : RESEARCH_SUBJECTS;
  const all = pool.flatMap((s) =>
    s.topics.map((topic) => ({ subjectId: s.id, subjectTitle: s.title, topic })),
  );
  if (!all.length) return null;

  const recent = readJson(RECENT_KEY, []);
  const fresh = all.filter((t) => !recent.includes(t.topic));
  const choices = fresh.length ? fresh : all;
  const picked = choices[Math.floor(Math.random() * choices.length)];

  writeJson(RECENT_KEY, [picked.topic, ...recent].slice(0, 30));
  return picked;
}

// The research session survives leaving the app to search online, a reload,
// or the phone closing the app. The timer counts from a saved end time.
// Shape: { subjectId, subjectTitle, topic, status: "idle" | "running" |
// "paused", endsAt, remaining }
export function loadResearchSession() {
  return readJson(SESSION_KEY, null);
}

export function saveResearchSession(session) {
  writeJson(SESSION_KEY, session);
}

export function clearResearchSession() {
  writeJson(SESSION_KEY, null);
}

export function researchSecondsLeft(session, now = Date.now()) {
  if (!session) return RESEARCH_SECONDS;
  if (session.status === "running") {
    return Math.max(0, Math.ceil((session.endsAt - now) / 1000));
  }
  return session.remaining ?? RESEARCH_SECONDS;
}
